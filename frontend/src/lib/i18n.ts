export function setLocale(locale: Locale | undefined): void {
  setActiveLocale(locale === 'de' ? 'de' : 'en')
}

export function t(key: LocalizationKey, values: Record<string, string | number> = {}): string {
  const catalogue = getActiveLocale() === 'de' ? german : english
  return Object.entries(values).reduce<string>(
    // split/join rather than a single replace: a placeholder that repeats in one
    // string (there is none today, but nothing prevents a future translation from
    // needing it) must not silently lose its second occurrence.
    (message, [name, value]) => message.split(`{${name}}`).join(String(value)),
    String(catalogue[key])
  )
}

/**
 * Pluralization for the small set of strings whose count can reach a language-specific
 * plural category (e.g. German's singular "1 Tag" vs plural "2 Tage"). `base` must have a
 * matching `${base}_other` key in both catalogues; a `${base}_one` key is used when the
 * active locale's plural rules select the "one" category for `count`.
 */
export function tCount(
  base: string,
  count: number,
  values: Record<string, string | number> = {}
): string {
  const catalogue = getActiveLocale() === 'de' ? german : english
  const category = new Intl.PluralRules(getActiveLocale() === 'de' ? 'de' : 'en').select(count)
  const candidate = `${base}_${category}`
  const key = (candidate in catalogue ? candidate : `${base}_other`) as LocalizationKey
  return t(key, { count, ...values })
}

export function pauseLabel(reason: PauseReason): string {
  if (reason === 'manual') return t('phase_paused')
  return t('phase_paused_reason', { reason: t(`pause_reason_${reason}` as LocalizationKey) })
}

export function watchStateLabel(status: WatchStatus | null): string {
  if (!status) return t('diagnostics_checking')
  if (!status.available) return t('watch_state_unavailable')
  if (!status.paired) return t('watch_state_unpaired')
  return status.reachable ? t('watch_state_ready') : t('watch_state_unreachable')
}
